// Bundles the sandboxed-preview React runtime (scripts/preview-runtime-entry.mjs) into a
// single minified classic script, emitted as a TS module that exports the script *source*
// as a string (lib/preview/react-runtime.generated.ts). The preview iframe inlines that
// source directly into its srcDoc rather than loading it over the network: the iframe is
// sandboxed with only `allow-scripts` (opaque origin, no cookies), so a `<script src>` to a
// deployment-protected preview 302s to SSO and never defines window.React. Inlining removes
// that network dependency entirely. Runs as an npm `prebuild` step and the output is committed
// so `next dev`, `next build`, and tests have it without a manual build.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { writeFile } from "node:fs/promises";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const result = await build({
  entryPoints: [resolve(here, "preview-runtime-entry.mjs")],
  bundle: true,
  minify: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  define: { "process.env.NODE_ENV": '"production"' },
});

const source = result.outputFiles[0].text;
const outfile = resolve(root, "lib/preview/react-runtime.generated.ts");
const fileBody = `// GENERATED by scripts/build-preview-runtime.mjs — do not edit by hand.
// Minified React 19 + react-dom/client runtime, inlined into the sandboxed preview iframe.
export const REACT_RUNTIME_SOURCE = ${JSON.stringify(source)};
`;

await writeFile(outfile, fileBody, "utf8");

console.log(`Built lib/preview/react-runtime.generated.ts (${source.length} bytes of runtime)`);
